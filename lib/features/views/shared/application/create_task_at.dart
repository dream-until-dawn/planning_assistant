/// 「在这儿新建一条」（FR-VIEW-07）。
///
/// ## 为什么快速新增要带上下文
///
/// 需求的验收原话是「在时间轴 14:00 处长按新增，新任务默认时间为 14:00」。
/// 在这之前，四个视图的加号走的都是同一个**无参**回调，
/// 于是新建表单永远是一张白纸：日历上翻到 9/20 点加号，
/// 建出来的任务落在「随时」区，**不在 9/20**。
/// 用户得再手动选一次那个他刚刚正看着的日期。
///
/// 上下文分两层，都可以缺：
///  · 日期 —— 四个视图都有（共享的聚焦日，view-specs §0.2）；
///  · 时刻 —— 只有能指到某一刻的视图给得出（时间轴长按、甘特长按）。
///
/// 两个都为空＝一张白纸，与从前一样。**这是有意保留的**：
/// 设置页里那个「新建」入口不在任何一天的语境里，
/// 硬塞一个「今天」会让它看起来像用户选的。
