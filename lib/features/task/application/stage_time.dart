/// 阶段时间的两种表示之间的换算（data-model §4.1）。
///
/// **存的是相对偏移，看的是绝对时刻。**
///
/// 存偏移的理由是重复：一条每周发生的阶段事项，它的阶段该写哪一周的日期？
/// 写不出来。偏移则对每一次发生都成立，而且整体挪动任务时阶段自动跟随。
///
/// 但偏移不能拿给人看 ——「+1440 分钟」谁也读不出是哪天。所以界面上
/// 一律显示绝对时刻，编辑时换算回偏移（§4.1 最后一段）。
///
/// **换算本身已经挪到 `core/time/date_and_minute.dart`** —— 领域层算
/// 任务的有效跨度（§4.7）时也要用它，而 domain 够不到 features。
/// 这里只剩一个转发，保留是因为「阶段时间怎么换算」在编辑器一侧
/// 是个有名字的概念，值得有个落点。
